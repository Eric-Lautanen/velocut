// crates/velocut-core/src/transitions/mod.rs
//
// Transition system for VeloCut.
//
// ╔══════════════════════════════════════════════════════════════╗
// ║  HOW TO ADD A TRANSITION — one line, everything else is auto ║
// ╚══════════════════════════════════════════════════════════════╝
//
//   1. Create `transitions/my_transition.rs`, impl `VideoTransition`
//      (all 6 required methods: kind, label, icon, build, apply, apply_rgba).
//      `apply`      → packed YUV420P (encode path).
//      `apply_rgba` → packed RGBA (playback/scrub path); use rayon `par_chunks_mut`
//                     over rows, must be stateless across rows.
//
//   2. Add ONE line to `declare_transitions!` below:
//        my_transition::MyTransition => MyKind,
//
//   Done. TransitionKind variant, registry, badge, tooltip, popup button,
//   duration slider, encode, and preview all pick it up automatically.
//   No other changes needed anywhere.
//
// ── Architecture ─────────────────────────────────────────────────────────────
//
//   Layer 1 — Serialized types  (`TransitionKind`, `TransitionType`,
//             `TimelineTransition`, `ClipTransition`)
//             These are written to the project file. Never rename/remove
//             existing TransitionKind variants without a migration path.
//
//   Layer 2 — `VideoTransition` trait
//             Pure pixel algorithm. Receives packed YUV420P slices + alpha,
//             returns blended packed slice. No FFmpeg types cross this boundary.
//
//   Layer 3 — Registry  (`registered()` for UI, `registry()` for encode)
//             Built from `declare_transitions!`. UI iterates `registered()`;
//             encode does O(1) lookup via `registry()`. Cut is never in either
//             — callers short-circuit on `TransitionKind::Cut`.

pub mod helpers;

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::OnceLock;
use uuid::Uuid;

// ── Drop-in registration ──────────────────────────────────────────────────────
//
// To add a transition:     append `module::Struct => KindVariant,` here.
// To disable a transition: comment it out. The KindVariant must stay in the
//                          serialized enum (generated below) for project-file
//                          safety, but the impl can be absent.
//
// The macro generates ALL of:
//   • `mod` declarations for each module
//   • The entire `TransitionKind` enum (Cut is always prepended)
//   • `make_entries()` used by `registered()` and `registry()`
//
// Nothing else in this file needs to change when a transition is added.

macro_rules! declare_transitions {
    ( $( $module:ident :: $struct:ident => $kind:ident ),* $(,)? ) => {
        $( mod $module; )*

        /// Identifies which algorithm to use. Generated by `declare_transitions!`.
        ///
        /// `Cut` is always present. All other variants come from the macro.
        /// `Copy` so the registry HashMap can key on it cheaply.
        ///
        /// **Never rename or remove existing variants** — they are written to
        /// project files and must deserialize cleanly forever.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
        pub enum TransitionKind {
            Cut,
            $( $kind, )*
        }

        fn make_entries() -> Vec<Box<dyn VideoTransition>> {
            vec![ $( Box::new($module::$struct) ),* ]
        }
    };
}

declare_transitions! {
    crossfade::Crossfade       => Crossfade,
    dip_to_black::DipToBlack   => DipToBlack,
    dip_to_white::DipToWhite   => DipToWhite,
    iris::Iris                 => Iris,
    wipe::Wipe                 => Wipe,
    push::Push                 => Push,
    barn_doors::BarnDoors      => BarnDoors,
    clock_wipe::ClockWipe      => ClockWipe,
}

// ── Serialized project types ──────────────────────────────────────────────────

/// Serialized transition stored in `ProjectState`.
///
/// A plain struct — not a per-transition enum — because every transition shares
/// the same runtime parameter (`duration_secs: f32`). This means this struct
/// never needs to change when a new transition is added. Only the one line in
/// `declare_transitions!` changes.
///
/// Written to the project file. `kind` identifies the algorithm; `duration_secs`
/// is the overlap length in seconds (0.0 for Cut, ignored).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct TransitionType {
    pub kind: TransitionKind,
    pub duration_secs: f32,
}

impl Default for TransitionType {
    fn default() -> Self {
        TransitionType {
            kind: TransitionKind::Cut,
            duration_secs: 0.0,
        }
    }
}

impl TransitionType {
    /// General constructor — used by `VideoTransition::build()` impls.
    pub fn new(kind: TransitionKind, duration_secs: f32) -> Self {
        TransitionType {
            kind,
            duration_secs,
        }
    }

    /// Convenience constructor for a hard cut.
    pub fn cut() -> Self {
        TransitionType {
            kind: TransitionKind::Cut,
            duration_secs: 0.0,
        }
    }

    /// Duration this transition can actually occupy between two clips.
    ///
    /// The blend is a zone CENTRED on the cut, so each side contributes half the
    /// duration. Half of it must fit inside both neighbours, hence the `2 ×`
    /// factor. Enforcing it in one place is what keeps the timeline badge, the
    /// preview zone, the playback blend specs and the encoder from disagreeing
    /// about how long a transition is: a 3 s transition on a 0.4 s clip used to
    /// spill outside both clips, put a blend zone under the playhead while it sat
    /// on the PREDECESSOR clip, and decode past the end of the source on export.
    ///
    /// Returns 0.0 for `Cut`.
    pub fn clamped_secs(&self, clip_a_dur: f64, clip_b_dur: f64) -> f64 {
        if self.kind == TransitionKind::Cut {
            return 0.0;
        }
        (self.duration_secs as f64)
            .min(2.0 * clip_a_dur.max(0.0))
            .min(2.0 * clip_b_dur.max(0.0))
            .max(0.0)
    }
}

#[cfg(test)]
mod duration_clamp_tests {
    use super::*;

    fn tr(kind: TransitionKind, secs: f32) -> TransitionType {
        TransitionType::new(kind, secs)
    }

    #[test]
    fn clamped_secs_uses_the_requested_duration_when_clips_are_long() {
        assert_eq!(
            tr(TransitionKind::Crossfade, 1.0).clamped_secs(10.0, 10.0),
            1.0
        );
    }

    #[test]
    fn clamped_secs_shortens_to_the_shorter_neighbor() {
        // Half the zone must fit in each neighbour: 2 × the shorter clip.
        let three = tr(TransitionKind::Crossfade, 3.0);
        assert_eq!(three.clamped_secs(0.4, 10.0), 0.8);
        assert_eq!(three.clamped_secs(10.0, 0.7), 1.4);
        assert_eq!(three.clamped_secs(10.0, 1.5), 3.0);
    }

    #[test]
    fn clamped_secs_is_cut_if_duration_is_zero() {
        assert_eq!(TransitionType::cut().clamped_secs(1.0, 1.0), 0.0);
        assert_eq!(tr(TransitionKind::Iris, 0.0).clamped_secs(1.0, 1.0), 0.0);
    }

    #[test]
    fn clamped_secs_never_returns_a_negative_zone() {
        assert_eq!(tr(TransitionKind::Wipe, 1.0).clamped_secs(-1.0, 5.0), 0.0);
    }
}

/// Stored in `ProjectState`, serialized with the project.
///
/// Keyed by the UUID of the preceding `TimelineClip` so it survives clip
/// reordering without going stale.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TimelineTransition {
    pub after_clip_id: Uuid,
    pub kind: TransitionType,
}

/// Encode-only — built by `begin_render`, passed through `EncodeSpec`.
/// Not serialized.
#[derive(Clone, Debug)]
pub struct ClipTransition {
    /// Index into the sorted clip Vec (0 = between clips[0] and clips[1]).
    pub after_clip_index: usize,
    pub kind: TransitionType,
}

// ── VideoTransition trait ─────────────────────────────────────────────────────

/// Algorithm contract for all video transitions.
///
/// Implementors are zero-size (or config) structs — they hold no per-clip state.
/// Runtime parameters arrive through `TransitionType` at the call site; the
/// trait only receives what it needs to blend two frames.
///
/// # Buffer contract
/// `frame_a` and `frame_b` are packed YUV420P byte slices:
///   `[Y: w×h bytes][U: (w/2)×(h/2) bytes][V: (w/2)×(h/2) bytes]`
/// No stride padding. Produce them with `velocut_media::helpers::yuv::extract_yuv`
/// and write results back with `write_yuv`.
///
/// # Alpha convention
/// `alpha = 0.0` → 100 % frame_a (outgoing clip)
/// `alpha = 1.0` → 100 % frame_b (incoming clip)
/// Caller computes alpha from frame index and total overlap frame count via
/// `transitions::helpers::frame_alpha`.
///
/// # Performance
/// `apply()` is called once per blended frame. All inner loops must live
/// *inside* the impl — never make repeated trait calls from a pixel loop.
pub trait VideoTransition: Send + Sync {
    /// Discriminant for registry lookup. Must match the `TransitionKind`
    /// variant declared for this transition in `declare_transitions!`.
    fn kind(&self) -> TransitionKind;

    /// Human-readable label shown in the UI picker (e.g. `"Dissolve"`).
    fn label(&self) -> &'static str;

    /// Glyph shown on the timeline badge. Use a single Unicode geometric character
    /// (e.g. "○", "◔") — egui's default font does not include emoji.
    fn icon(&self) -> &'static str;

    /// Default overlap duration in seconds pre-filled in the UI when the user
    /// first selects this transition.
    fn default_duration_secs(&self) -> f32 {
        0.5
    }

    /// Construct the serialized `TransitionType` for this transition.
    ///
    /// Called by the UI when the user selects or adjusts a transition. The UI
    /// **never** constructs `TransitionType` directly — always calls this so
    /// the kind and duration are encapsulated in the impl.
    ///
    /// Implementations should return: `TransitionType::new(self.kind(), duration_secs)`
    fn build(&self, duration_secs: f32) -> TransitionType;

    /// Shortest meaningful duration in seconds. UI should clamp below this.
    fn min_duration_secs(&self) -> f32 {
        0.2
    }

    /// Longest meaningful duration in seconds. UI should clamp above this.
    fn max_duration_secs(&self) -> f32 {
        5.0
    }

    /// One-sentence description shown in tooltips.
    /// Empty string = no tooltip.
    fn description(&self) -> &'static str {
        ""
    }

    /// Blend `frame_a` and `frame_b` at `alpha` and return the packed result.
    ///
    /// `width` / `height` are luma plane dimensions in pixels.
    /// UV dims are `(width / 2, height / 2)`.
    fn apply(&self, frame_a: &[u8], frame_b: &[u8], width: u32, height: u32, alpha: f32)
        -> Vec<u8>;

    fn apply_rgba(
        &self,
        frame_a: &[u8],
        frame_b: &[u8],
        width: u32,
        height: u32,
        alpha: f32,
    ) -> Vec<u8>;

    /// Blend into `out`, reusing its allocation when it is already big enough.
    ///
    /// Playback calls this once per displayed frame during a transition. A fresh
    /// 5 MB frame buffer costs a page fault every 4 KiB it is written to, so
    /// allocating one per frame — which `apply_rgba` must do when it returns a
    /// `Vec` — spends more time faulting pages in than blending. Callers that hold
    /// a buffer across frames get the blend for the cost of the arithmetic.
    ///
    /// Implementations must leave `out` exactly `frame_a.len()` bytes long and
    /// must overwrite every byte (reused buffers arrive with the previous frame's
    /// pixels in them).
    ///
    /// The default allocates through `apply_rgba`, so an effect that does not
    /// bother to override this is still correct, just not allocation-free.
    fn apply_rgba_into(
        &self,
        frame_a: &[u8],
        frame_b: &[u8],
        width: u32,
        height: u32,
        alpha: f32,
        out: &mut Vec<u8>,
    ) {
        out.clear();
        out.extend_from_slice(&self.apply_rgba(frame_a, frame_b, width, height, alpha));
    }
}

// ── Registry ──────────────────────────────────────────────────────────────────

/// All registered transitions in stable display order.
///
/// Use for UI iteration (picker buttons, badge lookup). Cut is not included —
/// it is always a hardcoded "remove transition" action in the UI.
pub fn registered() -> Vec<Box<dyn VideoTransition>> {
    make_entries()
}

/// All registered transitions keyed by `TransitionKind` for O(1) lookup.
///
/// Use during encode and preview. Cut has no entry — short-circuit on
/// `TransitionKind::Cut` before calling this.
///
/// The registry is cached in a static `OnceLock` so it is built only once
/// and shared across all callers.
pub fn registry() -> &'static HashMap<TransitionKind, Box<dyn VideoTransition>> {
    static REGISTRY: OnceLock<HashMap<TransitionKind, Box<dyn VideoTransition>>> = OnceLock::new();
    REGISTRY.get_or_init(|| make_entries().into_iter().map(|t| (t.kind(), t)).collect())
}

#[cfg(test)]
mod blend_bench;

/// The `apply_rgba` / `apply_rgba_into` contract.
///
/// `apply_rgba_into` exists purely so playback can blend into a buffer it owns;
/// if the two ever disagree, the UI would show one picture and the encoder
/// another. These tests pin the contract for every registered effect rather than
/// for the ones written today.
#[cfg(test)]
mod buffer_reuse_tests {
    use super::*;

    const SIZES: [(u32, u32); 3] = [(8, 4), (37, 21), (64, 36)];

    /// Deterministic, non-uniform frames: a blend that reads the wrong plane or
    /// the wrong row shows up as a byte mismatch instead of matching by accident.
    fn frames(w: u32, h: u32) -> (Vec<u8>, Vec<u8>) {
        let len = (w * h * 4) as usize;
        let a = (0..len).map(|i| (i % 251) as u8).collect();
        let b = (0..len).map(|i| ((i * 7 + 3) % 253) as u8).collect();
        (a, b)
    }

    #[test]
    fn every_transition_blends_the_same_bytes_into_a_caller_owned_buffer() {
        let mut buf = Vec::new();
        for (w, h) in SIZES {
            let (a, b) = frames(w, h);
            for t in registered() {
                for step in 0..=10 {
                    let alpha = step as f32 / 10.0;
                    let want = t.apply_rgba(&a, &b, w, h, alpha);
                    // Dirty the buffer first: a reused buffer arrives holding the
                    // previous frame, and "overwrite every byte" is part of the
                    // contract — a partially stale frame would show as smeared
                    // pixels that no other test would catch.
                    buf.clear();
                    buf.resize(a.len(), 0xAB);
                    t.apply_rgba_into(&a, &b, w, h, alpha, &mut buf);
                    assert_eq!(
                        buf.len(),
                        a.len(),
                        "{} left a {}-byte buffer for a {}-byte frame at {w}×{h}",
                        t.label(),
                        buf.len(),
                        a.len()
                    );
                    assert_eq!(
                        buf,
                        want,
                        "{} disagree between apply_rgba and apply_rgba_into at {w}×{h}, alpha={alpha}",
                        t.label()
                    );
                }
            }
        }
    }

    #[test]
    fn a_reused_buffer_is_not_reallocated_or_partially_stale() {
        let (w, h) = (64, 36);
        let (a, b) = frames(w, h);
        let t = registry()
            .get(&TransitionKind::Crossfade)
            .expect("crossfade registered");

        // Pre-fill with garbage at the right length: every implementation must
        // overwrite all of it, because a reused buffer arrives dirty.
        let mut buf = vec![0xABu8; a.len()];
        let capacity = buf.capacity();

        for step in 0..=4 {
            let alpha = step as f32 / 4.0;
            t.apply_rgba_into(&a, &b, w, h, alpha, &mut buf);
            assert_eq!(buf.len(), a.len());
            assert_eq!(buf.capacity(), capacity, "blend reallocated the buffer");
            assert_eq!(buf, t.apply_rgba(&a, &b, w, h, alpha));
        }
    }

    #[test]
    fn a_resolution_change_resizes_the_reused_buffer() {
        let t = registry()
            .get(&TransitionKind::Crossfade)
            .expect("crossfade registered");
        let mut buf = Vec::new();

        // Grow, then shrink: playback meets both across a resolution change and
        // the buffer must follow the frame rather than the other way round.
        for (w, h) in [(8u32, 4u32), (64, 36), (8, 4)] {
            let (a, b) = frames(w, h);
            t.apply_rgba_into(&a, &b, w, h, 0.6, &mut buf);
            assert_eq!(buf.len(), a.len(), "{w}×{h}");
            assert_eq!(buf, t.apply_rgba(&a, &b, w, h, 0.6), "{w}×{h}");
        }
    }
}
